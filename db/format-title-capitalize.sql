-- Разовая правка: названия форматов должны начинаться с заглавной буквы.
-- Выполнить один раз в Neon SQL Editor.
--
-- api/admin-formats.js теперь делает это сам при сохранении; здесь —
-- бэкфилл того, что уже лежит в базе (в т.ч. форматы, где название по
-- ошибке совпало с кодом и показывалось на сайте как есть, например «mlm»).

UPDATE event_formats
SET title = UPPER(LEFT(title, 1)) || SUBSTRING(title FROM 2)
WHERE title <> '';
