-- Признак «показывать в общем списке» у подкатегории.
-- Выполнить один раз в Neon SQL Editor (после db/menu-subcategories.sql).
--
-- Зачем: в больших категориях (например «Напитки» почти на сотню позиций) на
-- главной странице «Всё меню» показывать всё подряд бессмысленно — крепкий
-- алкоголь, настойки и чай мешаются с тем, что стоит показать первым.
-- Отмеченные подкатегории попадают в общий список, остальные видны только
-- когда гость откроет саму категорию.
--
-- Если в категории не отмечено НИ ОДНОЙ подкатегории, показывается всё —
-- то есть по умолчанию поведение не меняется.

ALTER TABLE menu_subcategories
  ADD COLUMN IF NOT EXISTS featured BOOLEAN NOT NULL DEFAULT false;
